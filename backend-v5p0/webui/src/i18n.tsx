const catalogs: Record<Lang, Record<TranslationKey, string>> = { it, en };

interface I18n {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18n | null>(null);

function detectLang(): Lang {
  const stored = localStorage.getItem("ui_lang");
  if (stored === "it" || stored === "en") return stored;
  return navigator.language?.toLowerCase().startsWith("en") ? "en" : "it";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang);
  const setLang = (value: Lang) => {
    localStorage.setItem("ui_lang", value);
    setLangState(value);
  };
  const t = (key: TranslationKey, vars?: Record<string, string | number>) => {
    let text: string = catalogs[lang][key] ?? catalogs.it[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
    }
    return text;
  };
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}

export function LanguageSwitch() {
  const { lang, setLang, t } = useI18n();
  return (
    <span className="lang-switch" role="group" aria-label={t("lang.switch")}>
      {(["it", "en"] as const).map(code => (
        <button key={code} type="button" className={lang === code ? "selected" : ""} onClick={() => setLang(code)}>
          {t(code === "it" ? "lang.it" : "lang.en")}
        </button>
      ))}
    </span>
  );
}
